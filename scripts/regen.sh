#!/usr/bin/env bash
# Regenerate all recompiled C++ for futari (shell + 8 game-mode modules).
#
# generated/ is gitignored (large, derived). This script reproduces it from the
# XEX assets + the committed manifest/function hints.
#
# IMPORTANT: the 8 game-mode modules all load at base 0x88000000 and the SDK
# analyzer (v0.8.0) corrupts cross-module analysis when codegen-ed together in
# one manifest. So each module is codegen-ed in ISOLATION (own single-module
# manifest, placeholder guest_path — codegen only reads file_path), then the
# module_registry.cpp + dll_targets.cmake covering ALL modules are assembled by
# hand. See memory: futari-recomp-sdk-build.md.
#
# Usage: scripts/regen.sh   (run from repo root)
set -euo pipefail
cd "$(dirname "$0")/.."

REXGLUE="./thirdparty/rexglue-sdk/out/win-amd64/rexglue.exe"
MODS=(reco_normal reco_abnormal palm_normal palm_abnormal hirow_normal hirow_abnormal kiniro_normal kiniro_abnormal)

# 1. Entrypoint (default.xex) — uses futari_functions.toml hints. A
#    single-module manifest also (re)generates default/. Use reco_normal's.
echo "[regen] entrypoint + modules (isolated)"
for m in "${MODS[@]}"; do
  # Per-module function-entry hints (analyzer misses indirect-call targets, same
  # as the shell). Use <module>_functions.toml if present.
  mod_inc="[]"
  if [ -f "${m}_functions.toml" ]; then mod_inc="[\"${m}_functions.toml\"]"; fi
  printf '[project]\nname = "futari"\nsdk_version = "0.8.0.0"\ngame_root = "assets"\n\n[entrypoint]\nfile_path = "assets/default.xex"\nout_directory_path = "generated/default"\nincludes = ["futari_functions.toml"]\n\n[[modules]]\nguest_path = "x"\nfile_path = "assets/media/Module/%s.xex"\nout_directory_path = "generated/%s"\nincludes = %s\n' "$m" "$m" "$mod_inc" > .regen_solo.toml
  "$REXGLUE" codegen .regen_solo.toml >/dev/null
  echo "  [ok] $m"
done
rm -f .regen_solo.toml

# 2. Assemble the all-modules registry + dll_targets (codegen's versions only
#    list the last isolated module). guest_path uses the normalized forward-slash
#    form (NormalizeGuestPath maps game:\media\Module\<m>.xex to this).
echo "[regen] assembling module_registry.cpp + dll_targets.cmake"
{
  echo '// Auto-generated by scripts/regen.sh - module registry for all game modes.'
  echo '#include <rex/system/kernel_state.h>'
  echo 'void RegisterRecompiledModules(rex::system::KernelState* kernel_state) {'
  for m in "${MODS[@]}"; do
    printf '  kernel_state->RegisterRecompiledModule("%s.xex", "media/module/%s.xex", "futari_%s");\n' "$m" "$m" "$m"
  done
  echo '}'
} > generated/default/module_registry.cpp

{
  echo '# Auto-generated by scripts/regen.sh - DLL targets for all game modes.'
  echo ''
  for m in "${MODS[@]}"; do
    cat <<EOF
if(EXISTS "\${CMAKE_CURRENT_SOURCE_DIR}/generated/$m/sources.cmake")
    include(generated/$m/sources.cmake)
    set(DLL_SOURCES_$m \${GENERATED_SOURCES})
    unset(GENERATED_SOURCES)
    add_library(futari_$m SHARED \${DLL_SOURCES_$m})
    target_include_directories(futari_$m PRIVATE \${CMAKE_CURRENT_SOURCE_DIR} \${CMAKE_CURRENT_SOURCE_DIR}/generated/$m)
    target_link_libraries(futari_$m PRIVATE rex::runtime)
    set_target_properties(futari_$m PROPERTIES CXX_VISIBILITY_PRESET hidden)
    rexglue_configure_module_target(futari_$m HOST \${REXGLUE_HOST_TARGET})
endif()

EOF
  done
} > generated/default/dll_targets.cmake

echo "[regen] done. Now reconfigure + build (see README / memory)."
