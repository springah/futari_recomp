#!/usr/bin/env bash
# Regenerate src/launcher/launcher_font.h: the launcher's font as a Dear ImGui compressed C array.
#
# The font is Roboto Medium (Christian Robertson / Google, Apache License 2.0), "Version 2.001152; 2014", the copy
# Dear ImGui ships in misc/fonts/Roboto-Medium.ttf (thirdparty/rexglue-sdk/thirdparty/imgui, a submodule, so nothing
# is downloaded; upstream: https://github.com/googlefonts/roboto, https://github.com/ocornut/imgui/tree/master/misc/fonts).
# It is cut down to Latin (Basic Latin, Latin-1 Supplement, the typographic quotes, dashes, bullet and ellipsis) with
# fontTools' pyftsubset, then packed by ImGui's own misc/fonts/binary_to_compressed_c.cpp (stb_compress, -u8).
#
# Needs python3 (fontTools is installed into a venv under out/font, not system-wide) and a C++ compiler.
# Usage: scripts/make_launcher_font.sh   (from anywhere; writes src/launcher/launcher_font.h)
set -euo pipefail
cd "$(dirname "$0")/.."

IMGUI=thirdparty/rexglue-sdk/thirdparty/imgui
TTF="$IMGUI/misc/fonts/Roboto-Medium.ttf"
WORK=out/font
OUT=src/launcher/launcher_font.h
[ -f "$TTF" ] || { echo "ERROR: $TTF missing (git submodule update --init --recursive)" >&2; exit 1; }
mkdir -p "$WORK"

if [ ! -x "$WORK/venv/bin/pyftsubset" ]; then
  python3 -m venv "$WORK/venv"
  "$WORK/venv/bin/pip" install -q fonttools
fi
"$WORK/venv/bin/pyftsubset" "$TTF" \
  --unicodes="U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-2019,U+201C-201D,U+2022,U+2026" \
  --layout-features='kern' --no-hinting --desubroutinize \
  --output-file="$WORK/Roboto-Medium-latin.ttf"

CXX="${CXX:-c++}"
"$CXX" -O2 -std=c++17 -o "$WORK/binary_to_compressed_c" "$IMGUI/misc/fonts/binary_to_compressed_c.cpp"

{
  echo "// Generated by scripts/make_launcher_font.sh -- do not edit."
  echo "// Roboto Medium, Version 2.001152 (Copyright 2011 Google Inc.), Apache License 2.0 (THIRD-PARTY-NOTICES.txt):"
  echo "// Dear ImGui's misc/fonts/Roboto-Medium.ttf (upstream https://github.com/googlefonts/roboto), Latin subset."
  echo "#pragma once"
  (cd "$WORK" && ./binary_to_compressed_c -u8 Roboto-Medium-latin.ttf futari_launcher_font) | sed '/^\/\/ File:/d;/^\/\/ Exported using/d'
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$WORK/Roboto-Medium-latin.ttf") byte font, $(grep -o 'compressed_size = [0-9]*' "$OUT"))"
